def _pair_webvoyager_action_errors(
    actions: list[EnvAction],
    result_call_ids: list[str | None],
    action_errors: list[dict[str, Any]] | None,
    legacy_errors: list[str],
) -> dict[str, str]:
    """Attribute container model-action errors to the originating call."""
    paired: dict[str, str] = {}

    def add(index: int, message: str) -> None:
        if index < 0 or index >= len(result_call_ids):
            return
        call_id = result_call_ids[index]
        if not call_id:
            return
        paired[call_id] = (
            f"{paired[call_id]}\n{message}" if call_id in paired else message
        )

    paired_indices: set[int] = set()
    structured_legacy_counts: dict[str, int] = {}

    def invalid_arguments_text(index: int, text: str, *, name: str | None = None) -> str:
        action_name = str(
            name or (actions[index]["name"] if 0 <= index < len(actions) else "action")
        )
        raw_detail = str(text).removeprefix(f"{action_name}: ").strip()
        detail = model_visible_error_detail(
            raw_detail,
            fallback="arguments could not be interpreted",
        )
        return invalid_action_arguments_message(action_name, detail)

    for raw_record in action_errors or []:
        fallback_name = None
        if isinstance(raw_record, dict):
            raw_index = raw_record.get("index")
            if isinstance(raw_index, int) and 0 <= raw_index < len(actions):
                fallback_name = str(actions[raw_index].get("name") or "action")
        record = parse_container_action_error_record(
            raw_record,
            result_call_ids=result_call_ids,
            fallback_name=fallback_name,
        )
        if record is None:
            continue
        index = record.index
        name = record.name
        error = record.error or record.message
        if record.kind == "model_action":
            add(index, invalid_arguments_text(index, error, name=name))
            legacy_text = f"{name}: {error}"
            structured_legacy_counts[legacy_text] = structured_legacy_counts.get(legacy_text, 0) + 1
        else:
            add(index, tool_execution_error_message(name, "execution failed"))
        paired_indices.add(index)

    next_index = 0
    for error in legacy_errors:
        text = str(error)
        if structured_legacy_counts.get(text, 0) > 0:
            structured_legacy_counts[text] -= 1
            continue
        index = next(
            (
                i for i in range(next_index, len(actions))
                if i not in paired_indices and text.startswith(f"{actions[i]['name']}:")
            ),
            None,
        )
        if index is None:
            index = next(
                (i for i in range(len(actions) - 1, -1, -1) if i not in paired_indices),
                None,
            )  # unmatched → best effort, never dropped while any call remains
            if index is None:
                continue
        else:
            next_index = index + 1
        add(index, invalid_arguments_text(index, text))
        paired_indices.add(index)
    return paired


def _strip_web_text_coords(text: str) -> str:
    """Remove visual center coordinates that Qwen may confuse with [N] ids."""
    return _WEB_TEXT_COORD_RE.sub("", text)


def _web_observation_text(
    resp: dict[str, Any],
    *,
    strip_coords: bool,
    include_page_context_text: bool,
) -> str:
    if not include_page_context_text:
        return ""

    web_text = str(resp.get("web_text") or "")
    if strip_coords:
        web_text = _strip_web_text_coords(web_text)

    parts: list[str] = []
    url = str(resp.get("url") or "")
    title = str(resp.get("title") or "")
    if url:
        parts.append(f"CURRENT URL: {url}")
    if title:
        parts.append(f"PAGE TITLE: {title}")
    if web_text:
        parts.append(f"DOM:\n{web_text}")
    return "\n".join(parts)


def _web_rejection_feedback_text(
    resp: dict[str, Any],
    web_text: str,
    *,
    include_page_context_text: bool,
) -> str | None:
    if not include_page_context_text:
        return None
    if web_text:
        return web_text
    parts: list[str] = []
    url = str(resp.get("url") or "")
    title = str(resp.get("title") or "")
    if url:
        parts.append(f"CURRENT URL: {url}")
    if title:
        parts.append(f"PAGE TITLE: {title}")
    return "\n".join(parts) or "Current page context is unchanged."


