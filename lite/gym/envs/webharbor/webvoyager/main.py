def _healthz(url: str) -> bool:
    if not url:
        return False
    try:
        with urllib.request.urlopen(url.rstrip("/") + "/healthz", timeout=3) as r:
            data = json.loads(r.read())
        return bool(data.get("ok"))
    except (urllib.error.URLError, OSError, ValueError):
        return False


