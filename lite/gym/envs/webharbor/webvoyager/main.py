    def _require_eval_deps(self) -> None:
        """Fail fast at reset() if the VLM judge can't run.

        Pass ``skip_eval=True`` to run without evaluation.
        """
        if importlib.util.find_spec("openai") is None:
            raise EnvDepsMissingError(
                what="openai package not importable (needed for VLM judge)",
                install="pip install openai",
                see="lite/gym/envs/webharbor/webvoyager/README.md",
            )
        api_key_var = self._eval_config.get("api_key_env_var", "OPENAI_API_KEY")
        if not os.environ.get(api_key_var):
            raise EnvDepsMissingError(
                what=f"WebVoyager VLM judge needs {api_key_var} (set OPENAI_BASE_URL for a proxy)",
                install=f"export {api_key_var}=...   # or pass skip_eval=True to run without evaluation",
                see="lite/gym/envs/webharbor/webvoyager/README.md",
            )

    def _build_eval_config(self) -> dict[str, Any]:
        """Resolve final eval config: yaml defaults → per-run overlay → env vars."""
        cfg = dict(self._eval_config)
        cfg.setdefault("model", "gpt-4.1")
        cfg.setdefault("max_attached_imgs", 3)
        cfg.setdefault("api_key_env_var", "OPENAI_API_KEY")
        if os.environ.get("WEBHARBOR_WEBVOYAGER_EVAL_MODEL"):
            cfg["model"] = os.environ["WEBHARBOR_WEBVOYAGER_EVAL_MODEL"]
        base_url = os.environ.get("WEBHARBOR_WEBVOYAGER_EVAL_BASE_URL") or os.environ.get("OPENAI_BASE_URL")
        if base_url:
            cfg["base_url"] = base_url
        if os.environ.get("WEBHARBOR_WEBVOYAGER_EVAL_API_KEY_VAR"):
            cfg["api_key_env_var"] = os.environ["WEBHARBOR_WEBVOYAGER_EVAL_API_KEY_VAR"]
        return cfg

    async def _evaluate(self) -> tuple[float | None, dict[str, Any]]:
        """Evaluate the episode at its end (terminated or truncated).

        Returns (reward, eval_info). Reward is None when evaluation is skipped
        or the agent gave no answer; 0.0 or 1.0 when the judge ran.

        Judge runtime errors propagate so the rollout can retry (they must NOT
        be silently scored 0.0 — that would corrupt collected data).
        """
        if self._skip_eval:
            return None, {}

        if not self._agent_response:
            return None, {
                "agent_response": None,
                "eval_skipped": True,
                "eval_skip_reason": "no_agent_response",
            }

        return await asyncio.to_thread(self._vlm_evaluate_sync)

    def _vlm_evaluate_sync(self) -> tuple[float, dict[str, Any]]:
        """Synchronous GPT-4V judge call (runs in a thread via asyncio.to_thread).

        Follows the original WebVoyager auto_eval.py evaluation protocol:
        shows the task instruction, agent response, and the last N screenshots
        to a VLM and parses SUCCESS / NOT SUCCESS from the verdict.
        """
        import openai

        cfg = self._build_eval_config()
        model = cfg["model"]
        max_imgs = int(cfg.get("max_attached_imgs", 3))
        api_key_var = cfg["api_key_env_var"]
        api_key = os.environ.get(api_key_var, "")
        base_url = cfg.get("base_url")

        client = openai.OpenAI(api_key=api_key, base_url=base_url or None)

        # Build reference context
        ref_answer = self._task.get("reference_answer", "") or ""
        ref_type = self._task.get("reference_type", "possible") or "possible"
        ref_notice = self._task.get("reference_notice", "") or ""
        if ref_notice:
            ref_notice = f"\n(Note: {ref_notice.strip()})"

        user_text = _JUDGE_USER_TMPL.format(
            instruction=self._task.get("instruction", ""),
            reference_answer=ref_answer,
            reference_type=ref_type,
            reference_notice=ref_notice,
            answer=self._agent_response,
            num=min(max_imgs, len(self._screenshots)),
        )

        # Attach last max_imgs screenshots as base64 inline images
        image_parts: list[dict[str, Any]] = []
        for png_bytes in self._screenshots[-max_imgs:]:
            b64 = base64.b64encode(png_bytes).decode("ascii")
            image_parts.append({
                "type": "image_url",
                "image_url": {"url": f"data:image/png;base64,{b64}", "detail": "low"},
            })

        messages: list[dict[str, Any]] = [
            {"role": "system", "content": _JUDGE_SYSTEM_PROMPT},
            {
                "role": "user",
                "content": [{"type": "text", "text": user_text}] + image_parts + [
                    {"type": "text", "text": "Your verdict:\n"},
                ],
            },
        ]

        logger.info(
            "webharbor.webvoyager judge: task=%s model=%s imgs=%d answer=%r",
            self._task_id, model, len(image_parts), (self._agent_response or "")[:80],
        )

        for attempt in range(5):
            try:
                response = client.chat.completions.create(
                    model=model,
                    messages=messages,
                    max_tokens=1000,
                    temperature=0,
                    seed=42,
                )
                break
            except Exception as e:
                if attempt < 4 and ("429" in str(e) or "rate" in str(e).lower() or "RateLimitError" in type(e).__name__):
                    wait = 10 * (2 ** attempt)
                    logger.warning("webharbor.webvoyager judge rate-limited (attempt %d/5), retrying in %ds: %s", attempt + 1, wait, e)
                    time.sleep(wait)
                else:
                    raise
        verdict = response.choices[0].message.content or ""
        logger.info("webharbor.webvoyager judge verdict: %s", verdict[:300])

        if "NOT SUCCESS" in verdict:
            reward = 0.0
        elif "SUCCESS" in verdict:
            reward = 1.0
        else:
            # Malformed response — treat as failure but log for debugging
            logger.warning("webharbor.webvoyager judge returned no SUCCESS/NOT SUCCESS verdict: %r", verdict[:200])
            reward = 0.0

        return reward, {
            "agent_response": self._agent_response,
            "eval_model": model,
            "eval_verdict": verdict,
            "reward": reward,
        }

    # -----------------------------------------------------------------------
    # RPC transport
    # -----------------------------------------------------------------------

    def _post(self, path: str, body: dict[str, Any], *, timeout: float) -> dict[str, Any]:
        """POST to the container. ``timeout`` is required and must stay BELOW the
        deadline the caller is held to.

        This runs in a pool thread via ``asyncio.to_thread``. Cancelling that
        awaitable -- which is what ``StepTimeoutWrapper``'s ``asyncio.wait_for``
        does on expiry -- does not interrupt the thread; it keeps blocking in
        ``urlopen`` until its own timeout. A timeout longer than the caller's
        deadline therefore strands a pool worker for the difference, and every
        subsequent timeout strands another. Measured on a training host: with
        ``step_timeout`` 90s against a hardcoded 180s here, ~85 of the 96 pool
        threads sat in ``poll`` under an ENV_CONCURRENCY of 24, steps queued
        behind them, and the queueing produced more timeouts -- valid
        trajectories fell 127 -> 85 of 128 over four rollouts without recovering.
        """
        url = self._rpc_url.rstrip("/") + path
        data = json.dumps(body).encode()
        req = urllib.request.Request(url, data=data, method="POST", headers={"Content-Type": "application/json"})
        try:
            with urllib.request.urlopen(req, timeout=timeout) as resp:
                return json.loads(resp.read())
        except urllib.error.HTTPError as e:
            detail = e.read().decode("utf-8", errors="replace")
            if e.code == 503:
                raise CapacityExhausted(
                    what=f"webharbor.webvoyager container pool full ({path}): {detail}",
                    retry_after_s=60.0,
                ) from e
            raise RuntimeError(f"webharbor.webvoyager container {path} returned {e.code}: {detail}") from e

