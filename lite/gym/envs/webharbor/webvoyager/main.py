    async def reset(self) -> LiteEnvObservation:
        if not self._skip_eval:
            self._require_eval_deps()
        if self._instance_id is not None:
            await self.close()

        self._screenshots = []
        self._agent_response = None

        resp = await asyncio.to_thread(
            functools.partial(self._post, timeout=_RESET_RPC_TIMEOUT),
            "/reset",
            {
                "task_id": self._task_id,
                "upstream_id": self._task.get("upstream_id", ""),
                "instruction": self._task.get("instruction", ""),
                "start_url": self._task.get("start_url", "https://www.google.com/"),
                "site_slug": self._task.get("site_slug", ""),
                "max_steps": self.max_steps,
                "viewport": list(self._viewport),
                "fix_box_color": self._fix_box_color,
                "use_som": self._use_som,
                "cursor": self._cursor,
            },
        )
        self._instance_id = resp["instance_id"]
        self._step_count = 0

        # Decode the screenshot ONCE (off-loop) and share it between the evaluation
        # buffer and the observation — avoids a second, synchronous multi-MB
        # b64decode of the same payload on the event loop.
        png = await png_from_b64_async(resp.get("screenshot_b64"))
        if png:
            self._screenshots.append(png)
        raw_web_text = str(resp.get("web_text") or "")
        web_text = _web_observation_text(
            resp,
            strip_coords=self._strip_web_text_coords,
            include_page_context_text=self._include_page_context_text,
        )
        metadata = {
            "url": resp.get("url", ""),
            "title": resp.get("title", ""),
            "web_text": raw_web_text,
        }
        if web_text:
            metadata["model_web_text"] = web_text
        self._last_observation_image = png
        self._last_observation_text = _web_rejection_feedback_text(
            resp,
            web_text,
            include_page_context_text=self._include_page_context_text,
        )
        self._last_observation_metadata = {
            "url": resp.get("url", ""),
            "title": resp.get("title", ""),
            "web_text": raw_web_text,
            "downloads": [],
        }
        if web_text:
            self._last_observation_metadata["model_web_text"] = web_text

        return LiteEnvObservation(
            image=png,
            text=resp.get("instruction") or self._task.get("instruction", ""),
            metadata=metadata,
        )

    async def step(self, actions: list[RuntimeEnvAction]) -> LiteEnvStepResult:
        if self._instance_id is None:
            raise RuntimeError("webharbor.webvoyager step() called before reset()")
        input_actions = actions
        result_call_ids = ordered_tool_call_ids(input_actions)
        metadata = self.metadata
        actions_with_result_ids, action_errors = prepare_env_tool_calls(
            actions,
            metadata,
            defer_extra_schema_validation_for=_WEBHARBOR_WEBVOYAGER_SHAPE_ROUTED_EXTRA_TOOLS,
        )
        action_errors: dict[str, ToolErrorFeedback] = dict(action_errors)
        actions_to_send: list[EnvAction] = []
        sent_result_call_ids: list[str | None] = []
        extra_tool_schemas = metadata.extra_tool_schemas
        for action, result_call_id in actions_with_result_ids:
            name = action["name"]
            if name == "done":
                if result_call_id:
                    action_errors[result_call_id] = current_feedback(
                        unavailable_action_message(name)
                    )
                continue
            argument_error = _shape_routed_extra_argument_error(
                action,
                extra_tool_schemas,
            )
            if argument_error:
                if result_call_id:
                    action_errors[result_call_id] = current_feedback(argument_error)
                continue
            tool_feedback = standalone_tool_call_feedback(
                action,
                _KNOWN_STANDALONE_TOOL_NAMES,
                extra_tool_schemas,
                is_standalone_action_tool=_is_standalone_extra_call,
            )
            if tool_feedback is not None:
                if result_call_id:
                    action_errors[result_call_id] = tool_feedback
                continue
            if _is_standalone_extra_call(action):
                if not is_active_extra_tool_call(action, extra_tool_schemas):
                    if result_call_id:
                        action_errors[result_call_id] = current_feedback(
                            unavailable_action_message(name)
                        )
                    continue
            else:
                invalid_action = invalid_action_message(action, metadata.valid_actions)
                if invalid_action:
                    if result_call_id:
                        action_errors[result_call_id] = current_feedback(invalid_action)
                    continue
            if name == "wait":
                try:
                    duration = coerce_model_duration(
                        action["arguments"].get("duration", 1.0),
                        action_name="wait",
                    )
                except MODEL_ACTION_ERROR_TYPES as e:
                    record_model_action_error(
                        action_errors,
                        result_call_id,
                        e,
                        action_name=name,
                    )
                    continue
                action = {
                    **action,
                    "arguments": {**action["arguments"], "duration": duration},
                }
            if name in LITE_DESKTOP_KEY_ACTION_NAMES:
                try:
                    # This container drives SELENIUM (ActionChains + `Keys.*`), not
                    # Playwright — project to the W3C WebDriver code points the
                    # container's `_selenium_key` passes straight through. An
                    # unprojected token would be TYPED AS LITERAL TEXT there.
                    # ``keys`` is REQUIRED and must be non-empty: the container's
                    # `if keys:` presses nothing for an empty list, so accepting
                    # one returned a normal post-action screenshot for a keypress
                    # that never happened -- the model could not tell. A missing
                    # or empty list is a malformed argument, reported through the
                    # same ``record_model_action_error`` channel as a bad
                    # ``wait.duration`` or an unknown key token.
                    keys = project_model_keys(
                        action["arguments"].get("keys", []),
                        action_name=name,
                        backend="selenium",
                    )
                except MODEL_ACTION_ERROR_TYPES as e:
                    record_model_action_error(
                        action_errors,
                        result_call_id,
                        e,
                        action_name=name,
                    )
                    continue
                action = {
                    **action,
                    "arguments": {**action["arguments"], "keys": keys},
                }
            actions_to_send.append(action)
            sent_result_call_ids.append(result_call_id)

        # Budget is consumed by the TURN, not by whether anything was
        # executable -- a step whose calls were all rejected still cost the
        # model a turn. Incrementing after the early return let a model that
        # only ever emits invalid calls run forever (sibling
        # ``online_mind2web/main.py`` increments before the same branch).
        self._step_count += 1
        if not actions_to_send:
            # Skipping the RPC is correct -- there is nothing to execute -- but
            # the step that EXHAUSTS the budget still has to be scored. Without
            # this the episode ended ``truncated=True, reward=None`` and a
            # complete trajectory was silently thrown away. ``_evaluate`` is
            # host-side here (the container always returns ``reward: None``), so
            # the fast path can score without a round-trip. Mirrors the sibling
            # ``online_mind2web/main.py``.
            truncated = self._step_count >= self.max_steps
            reward: float | None = None
            eval_info: dict[str, Any] = {}
            if truncated:
                reward, eval_info = await self._evaluate()
            return build_tool_results_from_decisions(
                LiteEnvStepResult(
                    reward=reward,
                    terminated=False,
                    truncated=truncated,
                    info={
                        EXECUTED_ACTIONS_INFO_KEY: [],
                        "errors": [],
                        "downloads": self._last_observation_metadata.get("downloads", []),
                        "answer": self._agent_response,
                        **eval_info,
                    },
                ),
                ordered_call_ids=result_call_ids,
                continue_call_ids=result_call_ids,
                images=[self._last_observation_image],
                text=self._last_observation_text,
                metadata=self._last_observation_metadata,
                feedback=action_errors,
            )

        resp = await asyncio.to_thread(
            functools.partial(self._post, timeout=_STEP_RPC_TIMEOUT),
            "/step",
            {
                "instance_id": self._instance_id,
                "actions": [_to_container_action(a) for a in actions_to_send],
                "post_action_delay": self._post_action_delay,
                "cursor": self._cursor,
                # The host owns the budget: it is the side that sees the turns
                # whose calls were all rejected (the fast path above never reaches
                # the container). The container derives both its ``truncated`` flag
                # and the model-facing ``[Turn n/max]`` banner from this value.
                "step_count": self._step_count,
            },
        )

        terminated = bool(resp.get("terminated"))
        # Model-emitted calls that ENDED the episode. They get no continuation
        # observation: devs/migration/verify.py forbids a tool result for a
        # terminal call. Keyed on ``action["call_id"]`` and NOT on
        # ``result_call_id``, because an INTERNAL finish call has no ``call_id``
        # and the loop-detect wrapper's injected ``terminate`` carries the
        # intercepted NON-finish model call's id as ``_result_call_id`` -- that
        # call must still be answered. Gated on ``terminated`` because the
        # CONTAINER owns the verdict here: a finish call it did not honour leaves
        # a non-terminal step, whose calls all still need their result.
        terminal_call_ids = {
            action["call_id"]
            for action in actions_to_send
            if action["name"] in LiteFinishToolSet.get_tool_names() and action.get("call_id")
        } if terminated else set()
        truncated = bool(resp.get("truncated"))

        # Decode ONCE (off-loop); share between the eval buffer and the observation.
        # One result frame per EXECUTED action, in action order: the container
        # runs the whole batch, so it is the only side that can see the page
        # between two actions. ``screenshots_b64`` is the single owner of
        # this step's frames; ``/step`` returns no singular spelling.
        frames_b64 = resp["screenshots_b64"]
        pngs = [
            frame for frame in
            [await png_from_b64_async(entry) for entry in frames_b64]
            if frame is not None
        ]
        # R3: a GUI slot the host rejected owes a frame too, but it never
        # reaches the container so none comes back for it. Derive WHERE those
        # slots sat from the sent list -- no filter arm has to remember -- and
        # re-interleave. The host cannot capture mid-batch (the container runs
        # the whole batch in one RPC), so a rejected slot repeats the frame of
        # the action before it; that slot changed nothing, so the repeat is the
        # honest record.
        if pngs and len(actions_to_send) < len(actions_with_result_ids):
            sent_ids = [id(a) for a in actions_to_send]
            rebuilt: list[bytes] = []
            executed_frames = iter(pngs)
            for action, _rid in actions_with_result_ids:
                if id(action) in sent_ids:
                    rebuilt.append(next(executed_frames, pngs[-1]))
                else:
                    rebuilt.append(rebuilt[-1] if rebuilt else pngs[0])
            pngs = rebuilt
        png = pngs[-1] if pngs else None
        # The eval buffer is a TURN log, not a frame log: WebJudge scores the
        # observation the model was left with, so only the last frame joins it.
        if png:
            self._screenshots.append(png)

        # Capture agent answer (set by the container on a response() action)
        if resp.get("answer"):
            self._agent_response = resp["answer"]

        # Evaluate at episode end
        reward: float | None = resp.get("reward")
        eval_info: dict[str, Any] = {}
        if terminated or truncated:
            reward, eval_info = await self._evaluate()

        raw_web_text = str(resp.get("web_text") or "")
        web_text = _web_observation_text(
            resp,
            strip_coords=self._strip_web_text_coords,
            include_page_context_text=self._include_page_context_text,
        )
        obs_metadata = {
            "url": resp.get("url", ""),
            "title": resp.get("title", ""),
            "web_text": raw_web_text,
            "downloads": resp.get("downloads", []),
        }
        if web_text:
            obs_metadata["model_web_text"] = web_text
        self._last_observation_image = png
        self._last_observation_text = _web_rejection_feedback_text(
            resp,
            web_text,
            include_page_context_text=self._include_page_context_text,
        )
        self._last_observation_metadata = obs_metadata
        # Action failures are PER-CALL feedback, not page context: splicing them
        # into the shared web_text blob sent them to every call of the turn, so
        # the agent could not tell WHICH call failed. Pair them to the
        # originating call_id instead.
        container_action_errors = _pair_webvoyager_action_errors(
            actions_to_send,
            sent_result_call_ids,
            list(resp.get("action_errors") or []),
            list(resp.get("errors") or []),
        )
        action_errors.update({
            call_id: current_feedback(message)
            for call_id, message in container_action_errors.items()
        })
        return build_tool_results_from_decisions(
            LiteEnvStepResult(
                reward=reward,
                terminated=terminated,
                truncated=truncated,
                info={
                    EXECUTED_ACTIONS_INFO_KEY: resp.get("executed", []),
                    "errors": resp.get("errors", []),
                    "downloads": resp.get("downloads", []),
                    "answer": resp.get("answer"),
                    **eval_info,
                },
            ),
            ordered_call_ids=result_call_ids,
            continue_call_ids=[
                call_id for call_id in result_call_ids
                if call_id not in terminal_call_ids
            ],
            images=pngs,
            text=_web_rejection_feedback_text(
                resp,
                web_text,
                include_page_context_text=self._include_page_context_text,
            ),
            metadata=obs_metadata,
            feedback=action_errors,
        )

    async def close(self) -> None:
        self._last_observation_image = None
        self._last_observation_text = None
        self._last_observation_metadata = {}
        self._step_count = 0
        if self._instance_id is None:
            return
        iid = self._instance_id
        self._instance_id = None
        try:
            await asyncio.to_thread(
                functools.partial(self._post, timeout=_CLOSE_RPC_TIMEOUT),
                "/close",
                {"instance_id": iid},
            )
        except Exception as e:
            logger.warning("webharbor.webvoyager container close failed: %s", e)


