def _is_standalone_extra_call(action: EnvAction) -> bool:
    name = action["name"]
    args = action["arguments"]
    if name in _WEBHARBOR_STANDALONE_EXTRA_TOOLS:
        return True
    return (name == "click" and "index" in args) or (name == "scroll" and "pages" in args)


def _shape_routed_extra_argument_error(
    action: EnvAction,
    extra_tool_schemas: list[dict[str, Any]] | None,
) -> str | None:
    """Validate same-name SoM extras before they reach the RPC server.

    ``click``/``scroll`` can mean either coordinate GUI actions or SoM DOM-index
    extras. Once the model includes the SoM discriminator key, the call belongs
    to the extra-tool schema and malformed parameters must not fall through to
    coordinate execution or become container-dependent feedback.
    """
    name = action["name"]
    if name not in _WEBHARBOR_WEBVOYAGER_SHAPE_ROUTED_EXTRA_TOOLS:
        return None
    if not _is_standalone_extra_call(action):
        return None
    schema = next(
        (schema for schema in extra_tool_schemas or [] if tool_schema_name(schema) == name),
        None,
    )
    if schema is None:
        return None
    args = action["arguments"]
    if not tool_arguments_match_schema_route_keys(schema, args):
        return invalid_action_arguments_message(
            name,
            f"{name}.arguments do not match its tool schema",
        )

    errors = tool_schema_validation_errors(schema, args)
    if not errors:
        return None
    err = errors[0]
    path = ".".join(str(part) for part in err.path)
    field = f"{name}.arguments.{path}" if path else f"{name}.arguments"
    if err.validator == "type" and isinstance(err.validator_value, str):
        return invalid_action_arguments_message(
            name,
            schema_type_error_reason(field, err.validator_value),
        )
    if err.validator == "required":
        missing = str(err.message).split("'", 2)[1:2]
        if missing:
            return invalid_action_arguments_message(
                name,
                f"{name}.arguments.{missing[0]} is required",
            )
    return invalid_action_arguments_message(name, f"{field} {err.message}")


