"""MAI-Gym agents — one-step creation via AgentRegistry.

MAI-Gym-9B is a Qwen3.5-9B fine-tune with the stock Qwen3.5 chat template, so
the agents inherit :class:`Qwen3_5BaseAgent`: ``adapter.enable_thinking`` (on
for this family) opens the ``<think>`` block, and the inherited parse step
moves the reply's reasoning out of the replay sidecar into
``reasoning_content``. The family delta is ``preserve_thinking=True`` (both
platforms): MAI-Gym evaluates with ``token_native_history`` (paper Appendix
A.5), replaying each past reply verbatim, so every past assistant turn keeps
its ``<think>`` block instead of the template's default of dropping it.

Unparseable replies are regenerated up to ``max_parse_retries`` extra times
(default 3, upstream's ``MAX_ACTION_PARSE_RETRIES``), as upstream does per
platform: mobile resends the identical prompt; desktop appends the failed
reply and upstream's correction message to the rendered turn (only the latest
failure, never accumulated). Failed attempts never reach the trajectory.
Exhaustion keeps the last attempt, which the shared parse-failure final turns
terminal — cua-lite's equivalent of upstream's ``terminate(status="failure")``.

Usage::

    agent = AgentRegistry.get(
        "mai_gym@desktop@use",
        processor=processor,
        generate_fn=generate_fn,
        password="password",
    )
"""

from __future__ import annotations

import asyncio
import logging
from dataclasses import dataclass
from typing import Any

from PIL import Image

from lite.agents.models.qwen3_5.agent import Qwen3_5BaseAgent
from lite.agents.types import PredictResult
from lite.core import STATUS_COMPLETED, STATUS_TRUNCATED, LiteRLStep, LiteSample

logger = logging.getLogger(__name__)

# ``AdapterBasedAgent._predict_with_details``'s truncation-shaped finish reasons.
_TRUNCATION_FINISH_REASONS = ("length", "max_tokens", "context_length_exceeded")


@dataclass
class MAIGymBaseAgent(Qwen3_5BaseAgent):
    """Shared MAI-Gym prompt building: native thinking on, history reasoning kept."""

    #: Upstream ``MAX_ACTION_PARSE_RETRIES``: extra generations of a turn whose
    #: reply has a model-output error.
    max_parse_retries: int = 3

    def build_generation_prompt(self, messages: list[dict[str, Any]]) -> str:
        """Build the prompt with native thinking on and history reasoning kept."""
        if self.processor is None:
            raise RuntimeError("agent.processor is not set")
        return self.processor.apply_chat_template(
            messages,
            add_generation_prompt=True,
            tokenize=False,
            enable_thinking=self.adapter.enable_thinking,
            preserve_thinking=True,
        )

    async def _predict_with_details(
        self,
        lite_sample: LiteSample,
        *,
        processed_images: list[Image.Image | None],
        call_id_start: int = 0,
    ) -> PredictResult:
        """Regenerate the turn until a reply parses to an action.

        A reply with a model-output error (the shared final's parse-failure
        signal) is regenerated by :meth:`_regenerate`. Every attempt is stamped
        from the same ``call_id_start`` and only the last one is returned, so
        failed attempts never reach the trajectory. Exhaustion returns the last
        failed attempt, which the loop's shared parse-failure final turns
        terminal.
        """
        result = await super()._predict_with_details(
            lite_sample,
            processed_images=processed_images,
            call_id_start=call_id_start,
        )
        for attempt in range(self.max_parse_retries):
            if result.model_output_error is None:
                break
            logger.warning(
                "MAI-Gym reply unparseable (attempt %d of %d): %s; regenerating",
                attempt + 1,
                self.max_parse_retries + 1,
                result.model_output_error,
            )
            result = await self._regenerate(
                lite_sample,
                processed_images=processed_images,
                call_id_start=call_id_start,
                failed=result,
            )
        return result

    async def _regenerate(
        self,
        lite_sample: LiteSample,
        *,
        processed_images: list[Image.Image | None],
        call_id_start: int,
        failed: PredictResult,
    ) -> PredictResult:
        """Upstream mobile retry: generate again from the identical prompt."""
        return await super()._predict_with_details(
            lite_sample,
            processed_images=processed_images,
            call_id_start=call_id_start,
        )


@dataclass
class MAIGymMobileUseAgent(MAIGymBaseAgent, key="mai_gym@mobile@use"):
    """Mobile GUI-use registry entry."""


@dataclass
class MAIGymDesktopUseAgent(MAIGymBaseAgent, key="mai_gym@desktop@use"):
    """Desktop computer-use registry entry."""

    async def _regenerate(
        self,
        lite_sample: LiteSample,
        *,
        processed_images: list[Image.Image | None],
        call_id_start: int,
        failed: PredictResult,
    ) -> PredictResult:
        """Upstream computer-use retry: rendered turn + failed reply + correction turn.

        Only the latest failure rides along, never accumulated. The failed
        reply replays verbatim as the assistant turn (the chat template splits
        its ``</think>`` as for any history turn); the adapter owns the
        correction text. The tail is text-only, so the images are unchanged.

        Generate / parse / RL-step below mirror
        ``AdapterBasedAgent._predict_with_details``; keep the two in sync.
        """
        agent_step, step_images, image_indices, _ = await asyncio.to_thread(
            self._render_generation_inputs,
            lite_sample,
            processed_images,
        )
        failed_response = failed.step.response
        agent_step = [
            *agent_step,
            {"role": "assistant", "content": [{"type": "text", "text": failed_response}]},
            {
                "role": "user",
                "content": [
                    {
                        "type": "text",
                        "text": self.adapter.render_parse_retry_feedback(failed_response),
                    }
                ],
            },
        ]
        prompt = await asyncio.to_thread(self.build_generation_prompt, agent_step)

        gen_response: dict[str, Any] = await self.generate_fn(
            prompt=prompt,
            images=step_images,
            messages=agent_step,
        )
        response: str = gen_response["response"]
        agent_message, lite_message, model_output_error = await asyncio.to_thread(
            self._parse_generation_response,
            response,
            call_id_start=call_id_start,
        )
        finish_reason = (gen_response.get("finish_reason") or "stop").lower()
        status = (
            STATUS_TRUNCATED if finish_reason in _TRUNCATION_FINISH_REASONS else STATUS_COMPLETED
        )
        step = LiteRLStep(
            prompt=prompt,
            image_indices=image_indices,
            response=response,
            response_tokens=list(gen_response.get("response_tokens") or []),
            response_log_probs=list(gen_response.get("response_log_probs") or []),
            status=status,
        )
        return PredictResult(
            lite_message=lite_message,
            agent_message=agent_message,
            step=step,
            model_output_error=model_output_error,
        )


